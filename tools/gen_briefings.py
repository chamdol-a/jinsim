def esc(s):
    return s.replace('\\','\\\\').replace('"','\\"')

# 관련 링크(공식 안내·신청 페이지 우선, 없으면 첫 출처) 자동 선택
OFFICIAL = ('univexpo','adiga','jinhak','goe-jinhakexpo','.go.kr','.ac.kr',
            'postech','iphak','admission','adms','oku.korea','skku','hufs',
            'uos','kaist','ewha','konkuk','use.go.kr','khu.ac')
def pick_link(d):
    for nm,url in d['sources']:
        low = url.lower()
        if any(m in low for m in OFFICIAL):
            return url
    return d['sources'][0][1]

def render(d):
    L = []
    a = L.append
    a('    {')
    a('      id: "%s",' % d['id'])
    a('      category: "briefing",')
    a('      date: "%s",' % d['date'])
    title = '[%s] %s' % (d['label'], d['title'])
    a('      title: "%s",' % esc(title))
    a('      summary: "%s",' % esc(d['summary']))
    tags = ', '.join('"%s"' % t for t in (d['tags'] + ["2027대입"]))
    a('      tags: [%s],' % tags)
    a('      sources: [')
    for i,(nm,url) in enumerate(d['sources']):
        comma = ',' if i < len(d['sources'])-1 else ''
        a('        { name: "%s", url: "%s" }%s' % (esc(nm), url, comma))
    a('      ],')
    a('      link: "%s",' % pick_link(d))
    # body
    body = []
    body.append('        <p class="lead-p">%s</p>' % d['intro'])
    body.append('        <h3>일정·장소</h3>')
    body.append('        <ul>')
    body.append('          <li>일정 — <b>%s</b></li>' % d['when'])
    body.append('          <li>장소 — %s</li>' % d['venue'])
    body.append('          <li>대상 — %s</li>' % d['target'])
    if d.get('parts'):
        body.append('          <li>참여·구성 — %s</li>' % d['parts'])
    body.append('        </ul>')
    if d.get('apply'):
        body.append('        <h3>신청·참고</h3>')
        body.append('        <p>%s</p>' % d['apply'])
    if d.get('note'):
        body.append('        <p>※ %s</p>' % d['note'])
    body.append('        <p>※ 일정·장소·신청 방법은 주최 측 사정으로 바뀔 수 있습니다. 아래 출처와 주최 기관 공식 공지에서 최신 정보를 반드시 확인하세요.</p>')
    a('      body: `')
    a('\n'.join(body))
    a('      `')
    a('    }')
    return '\n'.join(L)

