def build(d):
    """설명회 항목 → content/articles.json 에 넣을 기사 dict."""
    body = []
    body.append('        <p class="lead-p">%s</p>' % d['intro'])
    body.append('        <h3>일정·장소</h3>')
    body.append('        <ul>')
    body.append('          <li>일정 — <b>%s</b></li>' % d['when'])
    body.append('          <li>장소 — %s</li>' % d['venue'])
    body.append('          <li>대상 — %s</li>' % d['target'])
    if d.get('parts'):
        body.append('          <li>참여·구성 — %s</li>' % d['parts'])
    body.append('        </ul>')
    if d.get('apply'):
        body.append('        <h3>신청·참고</h3>')
        body.append('        <p>%s</p>' % d['apply'])
    if d.get('note'):
        body.append('        <p>※ %s</p>' % d['note'])
    body.append('        <p>※ 일정·장소·신청 방법은 주최 측 사정으로 바뀔 수 있습니다. '
                '아래 출처와 주최 기관 공식 공지에서 최신 정보를 반드시 확인하세요.</p>')
    return {
        "id": d['id'],
        "category": "briefing",
        "date": d['date'],
        "title": '[%s] %s' % (d['label'], d['title']),
        "summary": d['summary'],
        "tags": d['tags'] + ["2027대입"],
        "sources": [{"name": nm, "url": url} for nm, url in d['sources']],
        "link": pick_link(d),
        "body": '\n' + '\n'.join(body) + '\n      ',
    }

# sort by date desc, then id for stability
DATA.sort(key=lambda x: (x['date'], x['id']), reverse=True)

# content/articles.json 의 briefing 글 전체를 새로 만든 것으로 교체합니다.
